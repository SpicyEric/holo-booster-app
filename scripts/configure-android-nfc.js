// ============================================================================
// 11. ANDROID MANIFEST
// ============================================================================
function configureAndroidManifest() {
  console.log('\n📦 Configuring AndroidManifest.xml...');
  
  const manifestPath = path.join(ANDROID_PATH, 'app', 'src', 'main', 'AndroidManifest.xml');
  
  if (!fs.existsSync(manifestPath)) {
    console.log('   ⚠️ AndroidManifest.xml not found');
    return;
  }
  
  let content = fs.readFileSync(manifestPath, 'utf8');
  
  // Add NFC permission
  if (!content.includes('android.permission.NFC')) {
    content = content.replace(
      '<application',
      `<uses-permission android:name="android.permission.NFC" />
    <uses-feature android:name="android.hardware.nfc" android:required="false" />
    
    <application`
    );
    console.log('   ✅ NFC permissions added');
  }
  
  // Add Geolocation permissions
  if (!content.includes('ACCESS_FINE_LOCATION')) {
    content = content.replace(
      '<application',
      `<uses-permission android:name="android.permission.ACCESS_FINE_LOCATION" />
    <uses-permission android:name="android.permission.ACCESS_COARSE_LOCATION" />
    
    <application`
    );
    console.log('   ✅ Geolocation permissions added');
  }
  
  // Add NFC intent filters to MainActivity
  if (!content.includes('NDEF_DISCOVERED')) {
    content = content.replace(
      /<activity[^>]*android:name="[^"]*MainActivity"[^>]*>([\s\S]*?)<\/activity>/,
      (match) => {
        if (match.includes('NDEF_DISCOVERED')) return match;
        
        const nfcFilters = `
            <intent-filter>
                <action android:name="android.nfc.action.NDEF_DISCOVERED" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
            <intent-filter>
                <action android:name="android.nfc.action.TECH_DISCOVERED" />
            </intent-filter>
            <intent-filter>
                <action android:name="android.nfc.action.TAG_DISCOVERED" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
            <meta-data
                android:name="android.nfc.action.TECH_DISCOVERED"
                android:resource="@xml/nfc_tech_filter" />`;
        
        return match.replace('</activity>', nfcFilters + '\n        </activity>');
      }
    );
    console.log('   ✅ NFC intent filters added');
  }
  
  fs.writeFileSync(manifestPath, content, 'utf8');
}

