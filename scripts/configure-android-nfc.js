#!/usr/bin/env node

/**
 * Android NFC Configuration Script for Capacitor 5+
 * 
 * CLEAN SCRIPT - Capacitor 5/6 + AGP 8 compatible
 * 
 * This script:
 * - Patches android/app/build.gradle with correct SDK versions
 * - Patches AndroidManifest.xml with NFC permissions
 * - Creates NFC tech filter files
 * - Creates required Cordova plugins bridge module
 * - Does NOT create capacitor.build.gradle (deprecated in Capacitor 5+)
 * - Does NOT reference :capacitor-app (doesn't exist)
 * 
 * Usage: node scripts/configure-android-nfc.js
 * 
 * Build order:
 *   npm install
 *   npm run build
 *   npm install @capacitor/android
 *   npx cap add android
 *   node scripts/configure-android-nfc.js
 *   npx cap sync android
 *   npx cap open android
 */

