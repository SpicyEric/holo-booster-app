// ============================================================================
// 5. CONFIGURE ROOT BUILD.GRADLE - No allprojects repositories
// ============================================================================
function configureRootBuildGradle() {
  console.log('\n📦 Configuring root build.gradle...');
  
  const buildPath = path.join(ANDROID_PATH, 'build.gradle');
  
  // Clean root build.gradle - NO allprojects block (repos in settings.gradle)
  const content = `// build.gradle (root) - Generated by configure-android-nfc.js
// Capacitor 5+ / AGP 8 compatible
// NO allprojects repositories - all repos managed in settings.gradle!

buildscript {
    ext.kotlin_version = '${KOTLIN_VERSION}'
    
    repositories {
        google()
        mavenCentral()
    }
    
    dependencies {
        classpath "com.android.tools.build:gradle:${AGP_VERSION}"
        classpath "org.jetbrains.kotlin:kotlin-gradle-plugin:$kotlin_version"
    }
}

// Disable test and lint tasks for Capacitor/Cordova plugins
// Prevents Kotlin version compatibility issues
subprojects {
    afterEvaluate { project ->
        if (project.name.contains('capacitor') || 
            project.name.contains('cordova') ||
            project.name.contains('nfc') || 
            project.name.contains('geolocation')) {
            
            project.tasks.matching { task ->
                def name = task.name.toLowerCase()
                name.contains('test') || name.contains('lint')
            }.configureEach { task ->
                task.enabled = false
            }
        }
    }
}

task clean(type: Delete) {
    delete rootProject.buildDir
}
`;
  
  fs.writeFileSync(buildPath, content, 'utf8');
  console.log(`   ✅ Kotlin version → ${KOTLIN_VERSION}`);
  console.log(`   ✅ AGP version → ${AGP_VERSION}`);
  console.log('   ✅ No allprojects block (repos in settings.gradle)');
}

