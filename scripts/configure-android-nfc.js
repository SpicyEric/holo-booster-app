// 9. CREATE CAPACITOR-CORDOVA-ANDROID-PLUGINS MODULE
// ============================================================================
function createCordovaPluginsModule() {
  console.log('\n📦 Creating capacitor-cordova-android-plugins module...');
  
  const cordovaDir = path.join(ANDROID_PATH, 'capacitor-cordova-android-plugins');
  
  if (!fs.existsSync(cordovaDir)) {
    fs.mkdirSync(cordovaDir, { recursive: true });
  }
  
  // Create build.gradle
  const buildGradle = `// capacitor-cordova-android-plugins - Generated by configure-android-nfc.js
// NO repositories here - all repos in settings.gradle!

apply plugin: 'com.android.library'

android {
    namespace "capacitor.cordova.android.plugins"
    compileSdk 34
    
    defaultConfig {
        minSdk 22
        targetSdk 34
    }
    
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_17
        targetCompatibility JavaVersion.VERSION_17
    }
    
    buildTypes {
        release {
            minifyEnabled false
        }
    }
}

dependencies {
    implementation project(':capacitor-android')
}
`;
  
  fs.writeFileSync(path.join(cordovaDir, 'build.gradle'), buildGradle);
  
  // Create src directory
  const srcDir = path.join(cordovaDir, 'src', 'main');
  if (!fs.existsSync(srcDir)) {
    fs.mkdirSync(srcDir, { recursive: true });
  }
  
  // Create AndroidManifest.xml
  const manifest = `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
</manifest>
`;
  
  fs.writeFileSync(path.join(srcDir, 'AndroidManifest.xml'), manifest);
  
  console.log('   ✅ Module created with build.gradle and AndroidManifest.xml');
}

// ============================================================================
// 9. PATCH CAPACITOR-ANDROID BUILD.GRADLE
// ============================================================================
function patchCapacitorAndroid() {
  console.log('\n📦 Patching capacitor-android...');
  
  const capPath = path.join(NODE_MODULES_PATH, '@capacitor', 'android', 'capacitor', 'build.gradle');
  
  if (!fs.existsSync(capPath)) {
    console.log('   ⚠️ capacitor-android not found');
    return;
  }
  
  let content = fs.readFileSync(capPath, 'utf8');
  
  // Remove all repositories blocks
  content = content.replace(/\n*repositories\s*\{[\s\S]*?\n\}\n*/g, '\n');
  
  // Update Java version
  content = content.replace(/JavaVersion\.VERSION_\d+/g, 'JavaVersion.VERSION_17');
  
  fs.writeFileSync(capPath, content, 'utf8');
  console.log('   ✅ Removed repositories, Java → 17');
}

