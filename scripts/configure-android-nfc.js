// ============================================================================
// 9. PATCH CAPACITOR-ANDROID IN NODE_MODULES
// ============================================================================
function patchCapacitorAndroid() {
  console.log('\n📦 Patching capacitor-android module...');
  
  const capPath = path.join(NODE_MODULES_PATH, '@capacitor', 'android', 'capacitor', 'build.gradle');
  
  if (!fs.existsSync(capPath)) {
    console.log('   ⚠️ capacitor-android build.gradle not found (may not be installed yet)');
    return;
  }
  
  let content = fs.readFileSync(capPath, 'utf8');
  let modified = false;
  
  // Remove repositories blocks (repos managed in settings.gradle)
  if (content.includes('repositories {')) {
    content = content.replace(/\n*repositories\s*\{[\s\S]*?\n\}\n*/g, '\n');
    modified = true;
  }
  
  // Update Java version to 17
  if (content.includes('JavaVersion.VERSION_11') || content.includes('JavaVersion.VERSION_1_8')) {
    content = content.replace(/JavaVersion\.VERSION_\d+/g, 'JavaVersion.VERSION_17');
    content = content.replace(/JavaVersion\.VERSION_1_8/g, 'JavaVersion.VERSION_17');
    modified = true;
  }
  
  if (modified) {
    fs.writeFileSync(capPath, content, 'utf8');
    console.log('   ✅ Removed repositories block');
    console.log('   ✅ Updated Java version → 17');
  } else {
    console.log('   ✅ Already configured');
  }
}

